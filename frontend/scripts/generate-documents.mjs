/**
 * Generates `src/lib/generated/<id>.generated.ts` for every agreement that has
 * a cover-page overlay.
 *
 * Two inputs, deliberately kept apart:
 *
 *   templates/<id>.md        verbatim Common Paper Standard Terms. Says which
 *                            values the agreement substitutes, and nothing about
 *                            how to ask for them.
 *   cover-pages/<id>.json    ours. Says what to call each value, what kind of
 *                            thing it is, and how to group it on a form.
 *
 * Common Paper publishes a cover page for the Mutual NDA alone, so for every
 * other agreement the second file is the part that did not exist. Splitting it
 * out rather than editing the templates keeps `templates/` verbatim, per
 * templates/README.md, and keeps the licence honest.
 *
 * The overlay is JSON rather than JavaScript because the backend reads the same
 * file at runtime to build its prompt. Authoring the labels twice, once per
 * language, is exactly the kind of drift no test would catch.
 *
 * Runs from `predev` and `prebuild`, like the Mutual NDA generator beside it.
 */
import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

import {
  parseStandardTerms,
  deriveFieldNames,
  validateOverlay,
  eachSegment,
} from "./document-parser.mjs";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "../..");
const TEMPLATES_DIR = path.join(REPO_ROOT, "templates");
const OVERLAYS_DIR = path.join(REPO_ROOT, "cover-pages");
const CATALOG_PATH = path.join(REPO_ROOT, "catalog.json");
const OUTPUT_DIR = path.resolve(SCRIPT_DIR, "../src/lib/generated");

/**
 * Which agreements have an overlay, and so can be drafted.
 *
 * Listed here rather than discovered by globbing the directory, so adding a
 * document is a deliberate edit that shows up in a diff next to the overlay it
 * enables. `catalog.json`'s `available` flag is checked against this list.
 */
const DOCUMENT_IDS = [
  "ai-addendum",
  "business-associate-agreement",
  "pilot-agreement",
  "service-level-agreement",
  "design-partner-agreement",
];

/**
 * Numbers each field's appearances through the document.
 *
 * Common Paper calls these values Variables: capitalised terms defined on the
 * cover page and referred to by name in the body. So the first appearance
 * spells the value out — "the Pilot Period (90 days from the Effective Date)" —
 * and later ones just name the term, which is how the agreements are meant to
 * read. Counting happens here rather than at render time so the on-screen
 * document and the markdown export cannot disagree about which use is first.
 */
function annotateOccurrences(nodes) {
  const counts = new Map();
  for (const node of nodes) {
    for (const segment of eachSegment(node.body)) {
      if (segment.kind !== "field") continue;
      const seen = counts.get(segment.field) ?? 0;
      segment.occurrence = seen;
      counts.set(segment.field, seen + 1);
    }
  }
  return nodes;
}

function moduleFor({ id, title, overlay, nodes, catalogEntry, attribution }) {
  const json = (value) => JSON.stringify(value, null, 2);
  const fields = overlay.sections.flatMap((section) => section.fields);

  return `// Generated by scripts/generate-documents.mjs — do not edit by hand.
// Sources: templates/${id}.md (verbatim Common Paper Standard Terms)
//          cover-pages/${id}.json (Prelegal's cover-page overlay)
// Run \`npm run generate:documents\` to refresh.
import type { GeneratedDocument } from "@/lib/generic/types";

/**
 * ${catalogEntry.name} — ${nodes.length} clauses, ${fields.length} fields to fill in.
 *
 * Common Paper publishes no cover page for this agreement. The fields below are
 * the substitution points its own Standard Terms name; the labels and hints
 * around them are ours, from cover-pages/${id}.json.
 */
const DOCUMENT: GeneratedDocument = {
  id: ${JSON.stringify(id)},
  name: ${JSON.stringify(catalogEntry.name)},
  title: ${JSON.stringify(title)},
  summary: ${JSON.stringify(catalogEntry.summary)},
  attachesTo: ${JSON.stringify(catalogEntry.attaches_to)},
  // These Standard Terms carry no licence line of their own — only the Mutual
  // NDA's do — so the catalog's attribution is baked in here at build time. It
  // has to travel into every generated document, and a document that had to
  // fetch its own licence notice could render without one.
  attribution: ${JSON.stringify(attribution)},
  parties: ${json(overlay.parties)},
  derived: ${json(overlay.derived ?? [])},
  sections: ${json(overlay.sections)},
  clauses: ${json(nodes)},
};

export default DOCUMENT;
`;
}

function indexModule(ids) {
  const imports = ids
    .map((id) => `import ${constantFor(id)} from "./${id}.generated";`)
    .join("\n");
  const entries = ids.map((id) => `  ${JSON.stringify(id)}: ${constantFor(id)},`).join("\n");

  return `// Generated by scripts/generate-documents.mjs — do not edit by hand.
import type { GeneratedDocument } from "@/lib/generic/types";

${imports}

/**
 * Every agreement the generic engine can draft, by catalog id.
 *
 * The Mutual NDA is deliberately absent: it keeps its own hand-written creator
 * at \`app/documents/mutual-nda\`, so it must never appear in the dynamic
 * route's \`generateStaticParams\` or the two would fight over the same path.
 */
export const DOCUMENT_REGISTRY: Record<string, GeneratedDocument> = {
${entries}
};

export const DRAFTABLE_DOCUMENT_IDS = Object.keys(DOCUMENT_REGISTRY);
`;
}

function constantFor(id) {
  return id.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
}

async function main() {
  try {
    await access(TEMPLATES_DIR);
    await access(OVERLAYS_DIR);
  } catch {
    console.warn(
      `[generate-documents] ${TEMPLATES_DIR} or ${OVERLAYS_DIR} not found; keeping the committed generated files.`,
    );
    return;
  }

  const catalog = JSON.parse(await readFile(CATALOG_PATH, "utf8"));
  await mkdir(OUTPUT_DIR, { recursive: true });

  for (const id of DOCUMENT_IDS) {
    const catalogEntry = catalog.documents.find((entry) => entry.id === id);
    if (!catalogEntry) {
      throw new Error(`cover-pages/${id}.json has no matching entry in catalog.json`);
    }

    const [markdown, overlayJson] = await Promise.all([
      readFile(path.join(TEMPLATES_DIR, `${id}.md`), "utf8"),
      readFile(path.join(OVERLAYS_DIR, `${id}.json`), "utf8"),
    ]);
    const overlay = JSON.parse(overlayJson);
    if (overlay.id !== id) {
      throw new Error(`cover-pages/${id}.json declares id ${overlay.id}`);
    }

    const { title, nodes } = parseStandardTerms(markdown, `templates/${id}.md`);
    const fieldNames = deriveFieldNames(nodes);
    validateOverlay(overlay, fieldNames, `cover-pages/${id}.json`);
    annotateOccurrences(nodes);

    await writeFile(
      path.join(OUTPUT_DIR, `${id}.generated.ts`),
      moduleFor({
        id,
        title,
        overlay,
        nodes,
        catalogEntry,
        attribution: catalog.attribution,
      }),
      "utf8",
    );
    console.log(
      `[generate-documents] ${id}: ${nodes.length} clauses, ${fieldNames.length} fields.`,
    );
  }

  await writeFile(path.join(OUTPUT_DIR, "index.ts"), indexModule(DOCUMENT_IDS), "utf8");
  console.log(`[generate-documents] Wrote ${DOCUMENT_IDS.length} documents.`);
}

await main();
